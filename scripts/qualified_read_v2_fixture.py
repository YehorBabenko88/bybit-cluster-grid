"""Deterministic synthetic producer/read fixture for C/D contract tests only.

No provider or PostgreSQL authority, exchange connection, or paper trading.
The old source row is generated by the actual canonical Data49 producer.
"""
import json
import time
from market_data.provenance import minute_record, producer
from market_data_v2.read_api import qualified_snapshot

SYNTHETIC_EPOCH="123e4567-e89b-42d3-a456-426614174000"
SOURCE_REVISION="a"*40


def build_fixture(*,now_ms=1800000120000):
    if type(now_ms) is not int or now_ms<120000 or now_ms>=2**63:
        raise ValueError("SYNTHETIC_CLOCK_INVALID")
    start=(now_ms//60000-1)*60000
    source=producer("synthetic-v2-contract",SOURCE_REVISION,
                    "wss://stream.bybit.com/v5/public/linear")
    source["epoch"]=SYNTHETIC_EPOCH
    row={
        "symbol":"BTCUSDT","start_ms":start,
        "source_event_start_ms":start+1,
        "source_event_end_ms":start+59000,
        "source_provenance":source,
        "open":1.0,"high":2.0,"low":1.0,"close":2.0,
        "buy_volume":1.0,"sell_volume":0.0,
        "delta":1.0,"trade_count":1,"poc_price":2.0,
        "quality_status":"GOOD","quality_reasons":[],
        "levels":[{"price":2.0,"buy_volume":1.0,"sell_volume":0.0,
                   "delta":1.0,"volume":1.0,"buy_count":1,"sell_count":0}]
    }
    source_record=minute_record(row,now_ms,"synthetic-v2-contract")
    snapshot=qualified_snapshot("BTCUSDT",1,
        reader=lambda symbol,limit,before_ms:[source_record],now_ms=now_ms)
    assert source_record["producer"]=="market_data"
    assert snapshot["status"]=="PARTIAL"
    assert snapshot["source_authenticity"]=="NOT_INDEPENDENTLY_ATTESTED"
    assert snapshot["execution_authority"] is False
    return {
        "fixture_schema":"grid.market-data-v2.synthetic-contract.v1",
        "synthetic_only":True,
        "now_ms":now_ms,
        "source_record":source_record,
        "qualified_read":snapshot,
        "provider_authenticated":False,
        "postgresql_witness":None,
        "paper_authorized":False
    }


if __name__=="__main__":
    print(json.dumps(build_fixture(now_ms=(int(time.time()*1000)//60000)*60000),
        sort_keys=True,allow_nan=False))
